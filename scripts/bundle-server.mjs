// Inline server/src/*.mjs into one self-contained CommonJS file for Node SEA packaging.
// Zero deps, offline. The server uses only `export function`/`export const` and
// `import {…} from './x.mjs'` / `import x from 'node:…'`, so a line-oriented transform is exact;
// anything else throws rather than emit a silently-broken bundle.
//   node scripts/bundle-server.mjs   ->  dist/server-bundle.cjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const SRC = path.join(ROOT, 'server', 'src');
const OUT = path.join(ROOT, 'dist', 'server-bundle.cjs');
const ENTRY = 'main';

function transform(name, src) {
  const exported = [];
  const lines = src.split('\n').map((line) => {
    if (/^#!/.test(line)) return ''; // drop shebang; the bundle is required, not run directly
    let m = line.match(/^import\s*\{([^}]*)\}\s*from\s*['"]\.\/([^'"]+)\.mjs['"];?\s*$/);
    if (m) return `const {${m[1]}} = __req(${JSON.stringify(m[2])});`;
    m = line.match(/^import\s+([A-Za-z0-9_$]+)\s+from\s*['"](node:[^'"]+)['"];?\s*$/);
    if (m) return `const ${m[1]} = require(${JSON.stringify(m[2])});`;
    m = line.match(/^import\s*\{([^}]*)\}\s*from\s*['"](node:[^'"]+)['"];?\s*$/);
    if (m) return `const {${m[1]}} = require(${JSON.stringify(m[2])});`;
    if (/^\s*import\s/.test(line)) throw new Error(`${name}: unsupported import -> ${line}`);
    m = line.match(/^export\s+function\s+([A-Za-z0-9_$]+)/);
    if (m) { exported.push(m[1]); return line.replace(/^export\s+/, ''); }
    m = line.match(/^export\s+(const|let|var|class)\s+([A-Za-z0-9_$]+)/);
    if (m) { exported.push(m[2]); return line.replace(/^export\s+/, ''); }
    if (/^\s*export\s/.test(line)) throw new Error(`${name}: unsupported export -> ${line}`);
    return line;
  });
  for (const n of exported) lines.push(`exports[${JSON.stringify(n)}] = ${n};`);
  return lines.join('\n');
}

const modules = fs.readdirSync(SRC).filter((f) => f.endsWith('.mjs')).sort();
let out = `'use strict';
// GENERATED by scripts/bundle-server.mjs — do not edit. Source: server/src/*.mjs
const __mods = Object.create(null);
const __cache = Object.create(null);
function __req(name) {
  if (name in __cache) return __cache[name];
  const factory = __mods[name];
  if (!factory) return require(name);
  const module = { exports: {} };
  __cache[name] = module.exports;
  factory(module.exports, __req, module);
  __cache[name] = module.exports;
  return __cache[name];
}
`;

for (const file of modules) {
  const name = path.basename(file, '.mjs');
  const body = transform(name, fs.readFileSync(path.join(SRC, file), 'utf8'));
  out += `__mods[${JSON.stringify(name)}] = function (exports, __req, module) {\n${body}\n};\n`;
}
out += `__req(${JSON.stringify(ENTRY)});\n`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(ROOT, OUT)} — ${modules.length} modules, ${(out.length / 1024).toFixed(1)} KiB`);
